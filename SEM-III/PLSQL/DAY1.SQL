/* CREATING TABLES */

CREATE TABLE CUST(CUSTNO NUMBER(3) PRIMARY KEY,CUSTNAME VARCHAR2(30),ADDLN1 VARCHAR2(30),ADDLN2 VARCHAR2(30),CITY VARCHAR(20),STATES VARCHAR(20),PHONE NUMBER(10));
CREATE TABLE ITEM(ITEMNO NUMBER(3)PRIMARY KEY,ITEMNAME VARCHAR2(25),ITEMPRICE NUMBER(10),QTY_ON_HAND NUMBER(3));
CREATE TABLE INVOICE(INVNO NUMBER(3) PRIMARY KEY,INVDATE DATE,CUSTNO NUMBER(3) REFERENCES CUST(CUSTNO));
CREATE TABLE INV_ITEM(INVNO NUMBER(3) REFERENCES INVOICE(INVNO),ITEMNO NUMBER(3) REFERENCES ITEM(ITEMNO),QTY_USED NUMBER(3));

