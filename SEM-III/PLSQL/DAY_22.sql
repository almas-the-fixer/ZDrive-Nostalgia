-- 4.	Display dept and emp table data where job_id =’clerk’ and salary>3200 using explicit cursor with for loop.

DECLARE
CURSOR C4 IS SELECT DEPT.DEPT_ID,DEPT.DNAME,EMPP.EID,EMPP.ENAME,EMPP.JOB,EMPP.SALARY FROM DEPT,EMPP WHERE DEPT.DEPT_ID = EMPP.DEPT_ID AND EMPP.JOB='CLERK' AND EMPP.SALARY>3200;
