-- 1.	Write a program in PL/SQL to create a table-based record using the %ROWTYPE attribute where emp_id pass as an argument by user.

DECLARE
E1 EMPP%ROWTYPE;
CURSOR C1 IS SELECT * FROM EMPP WHERE EID=&EID;
BEGIN
OPEN C1;
LOOP
FETCH C1 INTO E1;
EXIT WHEN C1%NOTFOUND;
DBMS_OUTPUT.PUT_LINE('ID: '||E1.EID||CHR(10)||'NAME: '||E1.ENAME||CHR(10)||'DEPT ID: '||E1.DEPT_ID||CHR(10)||'JOB: '||E1.JOB||CHR(10)||'SALARY: '||E1.SALARY);
END LOOP;
CLOSE C1;
END;
/

