-- 5.	Create a PL/SQL block to increase salary of employees in the department 50 using .if salary <15000 raise 0.15 else raise 0.10 using current of clause.

DECLARE
SAL NUMBER;
ID NUMBER;
CURSOR CC IS SELECT SALARY,EID FROM EMPP WHERE DEPT_ID=50;
BEGIN
OPEN CC;
LOOP
FETCH CC INTO SAL,ID;
EXIT WHEN CC%NOTFOUND;
IF SAL<15000 THEN
UPDATE EMPP SET SALARY=SALARY+(SALARY*0.15) WHERE EID=ID;
ELSE
UPDATE EMPP SET SALARY=SALARY+(SALARY*0.10) WHERE EID=ID;
END IF;
DBMS_OUTPUT.PUT_LINE('ROW UPDATED');
END LOOP;
CLOSE CC;
END;
/