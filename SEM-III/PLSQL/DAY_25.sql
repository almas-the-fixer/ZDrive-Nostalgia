-- Q. 2 Write and call a parameterized cursor that takes sailor name as an argument and return its age. Throw an exception if no sailor is found.

DECLARE
NAME SAILOR.SNAME%TYPE;
BDAY DATE;
CURSOR S1(NAME IN VARCHAR2) IS SELECT DOB FROM SAILOR WHERE SNAME=NAME;
BEGIN
OPEN S1('&NAME');
FETCH S1 INTO BDAY;
IF S1%NOTFOUND THEN
CLOSE S1;
RAISE_APPLICATION_ERROR(-20001,'NO SAILOR FOUND');
ELSE
DBMS_OUTPUT.PUT_LINE('BIRTHDAY OF ENTERED SAILOR IS: '||BDAY);
END IF;
END;
