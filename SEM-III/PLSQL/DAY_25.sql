-- Q. 1 Write a pl/sql block to call a procedure that counts total boats reserved by each sailor and display them. Also write a function that asks for boat id and displays its color.

-- ############################################################### --
CREATE OR REPLACE PROCEDURE CNTBT(ID IN NUMBER,CNT OUT NUMBER)
IS
BEGIN
SELECT COUNT(BID) INTO CNT FROM RESERVE GROUP BY SID;
END;
/

DECLARE
ID NUMBER;
CNT NUMBER;
BEGIN
CNTBT(&ID,CNT);
DBMS_OUTPUT.PUT_LINE('NO OF BOATS RESERVED ARE:'||CNT);
END;
