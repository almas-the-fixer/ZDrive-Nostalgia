CREATE OR REPLACE FUNCTION B_COLOR(ID NUMBER)
RETURN VARCHAR2
IS
CLR VARCHAR2(50);
BEGIN
SELECT COLOR INTO CLR FROM BOAT WHERE BID=ID;
RETURN CLR;
END;
/

DECLARE
ID NUMBER;
CLR VARCHAR2(50);
BEGIN
CLR := B_COLOR(&ID);
DBMS_OUTPUT.PUT_LINE('cOLOR OF BOAT IS: '||CLR);
END;
