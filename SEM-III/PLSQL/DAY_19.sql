-- QUESTION 5: Write a PL/SQL procedure named count_student based on comp_ ID. The procedure should take the following input parameter:
-- •	comp_id 

CREATE PROCEDURE COUNT_STUDENT(CID IN NUMBER,CC OUT NUMBER)
IS  BEGIN
SELECT COUNT(STUD_ID) INTO CC FROM COMP WHERE COMP_ID=CID;
END;
/

-- EXECUTION OF ABOVE PROCEDURE
DECLARE
ID NUMBER;
CNT NUMBER;
BEGIN
ID:=&ID;
COUNT_STUDENT(ID,CNT);
DBMS_OUTPUT.PUT_LINE('COUNT: '||CNT||CHR(10)||'ID: '||ID);
END;
