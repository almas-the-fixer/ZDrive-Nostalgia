-- QUESTION 3 : Create a PL/SQL procedure named retrieves the stud_id and competition name of an student based on their ID. The procedure should take the following input parameter:
-- stud_id 
-- The procedure should output the following:
-- STUD_ID
-- COMP_NAME

-- PROCEDURE FOR QUESTION 3:

CREATE PROCEDURE RETRIEVE (S_ID IN NUMBER,ST_ID OUT NUMBER,C_NAME OUT VARCHAR2)
IS  BEGIN
SELECT STUD_ID,COMP_NAME INTO ST_ID,C_NAME FROM COMP WHERE STUD_ID=S_ID;
END;
/

-- EXECUTION OF ABOVE PROCEDURE
DECLARE
C1 COMP%ROWTYPE;
BEGIN
RETRIEVE(116,C1.STUD_ID,C1.COMP_NAME);
DBMS_OUTPUT.PUT_LINE('DATA RETRIEVED:'||CHR(10)||'STUDENT ID: '||C1.STUD_ID||CHR(10)||'COMPETITION NAME: '||C1.COMP_NAME);
END;
/

