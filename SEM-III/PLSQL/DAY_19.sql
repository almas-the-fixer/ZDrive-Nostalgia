-- QUESTION 2: Write a PL/SQL procedure named update_competition that updates the competition ‘Chess’. The procedure should take the following input parameters:
-- compe_id 
-- Competition_name (New)

-- PROCEDURE FOR QUESTION 2

CREATE PROCEDURE UPDATE_COMPETITION (C_ID IN NUMBER,C_NAME IN VARCHAR2)
IS BEGIN
UPDATE COMP SET COMP_NAME=C_NAME WHERE COMP_ID=C_ID;
END;
/

