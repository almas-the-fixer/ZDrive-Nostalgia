-- 3.Create a PL/SQL program that uses an explicit cursor to calculate the total number of questions paper wise. 

DECLARE
TOTAL NUMBER;
PID EXAM.PAPER_ID%TYPE;
CURSOR S3 IS SELECT COUNT(QUESTION_NO),PAPER_ID FROM EXAM GROUP BY PAPER_ID;
BEGIN
OPEN S3;
LOOP
FETCH S3 INTO TOTAL,PID;
EXIT WHEN S3%NOTFOUND;
DBMS_OUTPUT.PUT_LINE('PAPER ID: '||PID||CHR(10)||'NO OF QUESTIONS: '||TOTAL);
END LOOP;
CLOSE S3;
END;
/

