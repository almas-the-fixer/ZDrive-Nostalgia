DECLARE
ID STUDENT.SID%TYPE;
NAME STUDENT.SNAME%TYPE;
TEST EXAM.EXAM_DATE%TYPE;
EID EXAM.EXAM_ID%TYPE;
PID PAPER.PAPER_ID%TYPE;
CURSOR S1(EEID NUMBER,PPID NUMBER) IS SELECT STUDENT.SID,STUDENT.SNAME,EXAM.EXAM_DATE FROM STUDENT,PAPER,EXAM WHERE STUDENT.SID = EXAM.SID AND PAPER.PAPER_ID = EXAM.PAPER_ID AND PAPER.PAPER_ID=PID AND EXAM.EXAM_ID=EID;
BEGIN
EID:=&EID;
PID:=&PID;
OPEN S1(EID,PID);
LOOP
FETCH S1 INTO ID,NAME,TEST;
EXIT WHEN S1%NOTFOUND;
DBMS_OUTPUT.PUT_LINE('STUDENT ID: '||ID||CHR(10)||'STUDENT NAME: '||NAME||CHR(10)||'EXAM DATE: '||TEST);
END LOOP;
CLOSE S1;
END;
