-- 5.	Write a PL/SQL block that uses a cursor to find the details of the employee who does not belongs to ‘sales’ department.

DECLARE
ID EMPLOYEE.EID%TYPE;
NAME EMPLOYEE.ENAME%TYPE;
TITLE EMPLOYEE.JOB%TYPE;
CURSOR E1 IS SELECT EID,ENAME,JOB FROM EMPLOYEE WHERE  DEPT NOT IN('SALES');
BEGIN
OPEN E1;
LOOP
FETCH E1 INTO ID,NAME,TITLE;
EXIT WHEN E1%NOTFOUND;
DBMS_OUTPUT.PUT_LINE('ID: '||ID);
DBMS_OUTPUT.PUT_LINE('NAME: '||NAME);
DBMS_OUTPUT.PUT_LINE('JOB: '||TITLE);
END LOOP;
CLOSE E1;
END;
/

