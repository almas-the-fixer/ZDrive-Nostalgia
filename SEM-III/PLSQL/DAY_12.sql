-- 7.	Write a PL/SQL block,  that uses a cursor to find the maximum salary of an employee.

DECLARE
SAL EMPLOYEE.SALARY%TYPE;
CURSOR E3 IS SELECT MAX(SALARY) FROM EMPLOYEE;
BEGIN
OPEN E3;
LOOP
FETCH E3 INTO SAL;
EXIT WHEN E3%NOTFOUND;
DBMS_OUTPUT.PUT_LINE('MAXIMUM SALARY: '||SAL);
END LOOP;
CLOSE E3;
END;
