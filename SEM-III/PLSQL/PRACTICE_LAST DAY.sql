--ANSWER 1:

CREATE OR REPLACE TRIGGER TRR1
BEFORE UPDATE ON STOCK
FOR EACH ROW
BEGIN
IF :NEW.S_QTY > :OLD.P_QTY
THEN
RAISE_APPLICATION_ERROR(-20001,'SOLD QUANTITY CANNOT EXCEED PURCHASED QTY I.E ITEM OUT OF STOCKS');
ELSE
DBMS_OUTPUT.PUT_LINE('TABLE UPDATED SUCCESSFULLY!!');
END IF;
END;
/

