CREATE OR REPLACE PROCEDURE DISPLAY_ITEM(ICD IN NUMBER)
IS
IM ITEM_MASTER%ROWTYPE;
BEGIN
SELECT * INTO IM FROM ITEM_MASTER WHERE ITEM_CODE=ICD;
