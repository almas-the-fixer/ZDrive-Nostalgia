-- CREATING DEMO EMP2 TABLE
CREATE TABLE EMP2(EID NUMBER(3),ENAME VARCHAR2(50),
JOB VARCHAR2(30) CHECK(JOB IN('CLERK','MANAGER','HR','ANALYST','SALESMAN')),
SALARY NUMBER(10));
