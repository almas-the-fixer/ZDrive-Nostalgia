-- INREASING SALARY ACCORDING TO JOB TITLE TAKEN FROM USER
DECLARE
EJOB EMP2.JOB%TYPE;
BEGIN
EJOB:='&JOB';
CASE EJOB
WHEN 'CLERK' THEN
UPDATE EMP2 SET SALARY=SALARY+SALARY*0.05 WHERE JOB=EJOB;
WHEN 'MANAGER' THEN
UPDATE EMP2 SET SALARY=SALARY+SALARY*0.075 WHERE JOB=EJOB;
WHEN 'HR' THEN
UPDATE EMP2 SET SALARY=SALARY+SALARY*0.025 WHERE JOB=EJOB;
ELSE
UPDATE EMP2 SET SALARY=SALARY+SALARY*0.1 WHERE JOB=EJOB;
END CASE;
END;
